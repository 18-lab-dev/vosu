//! Fixed non-overlapping publication partition; arrays and stable groups are whole values.
//! `Source` is the sampling lane, not an exclusive input dependency: status
//! gates regular values and progress reads a regular beatmap. See `dirty.rs`.

#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Source {
    Regular,
    Precise,
    Session,
}

macro_rules! pointers {
    ($( $name:ident => ($ns:literal, $path:literal, $source:ident), )*) => {
        #[derive(Clone, Copy, PartialEq, Eq, Debug)]
        #[repr(u16)]
        pub enum OsuPointer { $( $name, )* }
        impl OsuPointer {
            pub const ALL: &'static [Self] = &[$(Self::$name,)*];
            pub const fn ns(self) -> &'static str { match self { $(Self::$name => $ns,)* } }
            pub const fn pointer(self) -> &'static str { match self { $(Self::$name => $path,)* } }
            pub const fn source(self) -> Source { match self { $(Self::$name => Source::$source,)* } }
        }
    };
}
