#!/usr/bin/env python3
"""Verify the published SDK package (`vosu-plugin-api`) as an outsider sees it (AF.9, S0).

`verify` packages the crate with `cargo package --locked -p vosu-plugin-api`
(or takes an existing `.crate` with `--crate`), prints its SHA-256, and then
checks the archive bytes themselves rather than the workspace:

1. the member list is exactly the manifest's `include` set (licenses, README,
   sources, self-contained tests and the `vosu-package-check` example), with
   no traversal, links or workspace-relative files;
2. the normalized `Cargo.toml` has no path/git dependency, no workspace
   inheritance and no Cargo features, and the sources carry no
   workspace-internal surface (synchronous reads, bundled registration);
3. the archive is extracted under a fresh temporary directory with no
   `Cargo.toml` in any ancestor, and the package's own tests (including the
   `vosu-package-check` example's) pass there with its own `Cargo.lock`;
4. an isolated consumer workspace depends on the SDK only as a registry
   requirement (`vosu-plugin-api = "=<version>"`), builds and tests one
   serialized `Plugin` and one `ConcurrentPlugin` `cdylib` export, and its
   `cargo metadata` shows the SDK resolved from the extracted archive with no
   features and no package from this checkout;
5. probe consumers that request a removed private feature, the bundled
   `export_plugin!` arm or `PlanMemory` fail to build.

The consumer's registry requirement is satisfied from the extracted archive
through a command-line `[patch.crates-io]` entry, since the version is not on
crates.io before the OWNER-approved publication (AF.1); no consumer manifest
names a path or git source. Nothing is uploaded. `cargo publish --dry-run`
remains a separate, explicit step.

The pinned toolchain from rust-toolchain.toml is used for every cargo call
outside the workspace (`RUSTUP_TOOLCHAIN`).
"""

import argparse
import hashlib
import json
import os
from pathlib import Path, PurePosixPath
import re
import shutil
import subprocess
import sys
import tarfile
import tempfile
import tomllib

ROOT = Path(__file__).resolve().parents[1]
CRATE = "vosu-plugin-api"
CRATE_DIR = ROOT / "crates" / CRATE

# Generated by `cargo package` in addition to the manifest's `include` set.
GENERATED = {".cargo_vcs_info.json", "Cargo.lock", "Cargo.toml.orig"}
REQUIRED = {
    "Cargo.toml",
    "Cargo.toml.orig",
    "Cargo.lock",
    "README.md",
    "LICENSE-MIT",
    "LICENSE-APACHE",
    "src/lib.rs",
    "examples/vosu-package-check/main.rs",
}
# Workspace-internal surface that must never reach crates.io (AF.9).
FORBIDDEN_SOURCE = [
    (re.compile(r"\bPlanMemory\b"), "PlanMemory (vosu-plugin-internal)"),
    (re.compile(r"\bSyncReadBuffers\b"), "SyncReadBuffers (vosu-plugin-internal)"),
    (re.compile(r"\bread_plan_profile\b"), "read_plan_profile (vosu-plugin-internal)"),
    (re.compile(r"unstable-sync-reads"), "the removed unstable-sync-reads feature"),
    (re.compile(r"\(\s*bundled\b"), "a bundled export_plugin! arm"),
    (re.compile(r"\bvosu[-_]proptest\b"), "the unpublished vosu-proptest crate"),
]


def pinned_toolchain(root=ROOT):
    with open(root / "rust-toolchain.toml", "rb") as handle:
        return tomllib.load(handle)["toolchain"]["channel"]


def include_globs(manifest_text):
    """The `package.include` globs of the SDK's own Cargo.toml."""
    return tomllib.loads(manifest_text)["package"]["include"]


def glob_matches(path, pattern):
    """Cargo-style include matching for the patterns the SDK manifest uses."""
    if pattern == path:
        return True
    if "**" in pattern:
        prefix, _, suffix = pattern.partition("/**/")
        return path.startswith(prefix + "/") and PurePosixPath(path).match(suffix)
    return False


def check_members(prefix, members, globs):
    """Validate the archive's member list; returns the package-relative files.

    `members` is a list of (name, is_regular_file) pairs from the `.crate`.
    """
    errors = []
    files = []
    for name, regular in members:
        path = PurePosixPath(name)
        if path.is_absolute() or ".." in path.parts or not name.startswith(prefix + "/"):
            errors.append(f"{name}: outside the package root {prefix}/")
            continue
        relative = name[len(prefix) + 1 :]
        if not regular:
            errors.append(f"{relative}: not a regular file")
            continue
        if relative not in GENERATED and not any(glob_matches(relative, g) for g in globs):
            errors.append(f"{relative}: not in the manifest's include set")
        files.append(relative)
    for missing in sorted(REQUIRED - set(files)):
        errors.append(f"{missing}: missing from the package")
    return sorted(files), errors


def check_normalized_manifest(text):
    """The packaged (normalized) Cargo.toml must stand alone and expose no features."""
    errors = []
    manifest = tomllib.loads(text)
    package = manifest.get("package", {})
    if package.get("publish") is False:
        errors.append("package.publish is false")
    for key in ("license", "description", "repository", "readme"):
        if not package.get(key):
            errors.append(f"package.{key} is missing")
    if manifest.get("features"):
        errors.append(f"declares Cargo features {sorted(manifest['features'])} (AF.9: none)")
    if "workspace" in text:
        errors.append("still names a workspace")
    tables = [("dependencies", manifest.get("dependencies", {}))]
    tables.append(("dev-dependencies", manifest.get("dev-dependencies", {})))
    tables.append(("build-dependencies", manifest.get("build-dependencies", {})))
    for target in manifest.get("target", {}).values():
        for kind in ("dependencies", "dev-dependencies", "build-dependencies"):
            tables.append((kind, target.get(kind, {})))
    for kind, dependencies in tables:
        for name, spec in dependencies.items():
            if isinstance(spec, dict) and ("path" in spec or "git" in spec):
                errors.append(f"{kind}.{name} has a path or git source")
            if name.startswith("vosu-"):
                errors.append(f"{kind}.{name} is a workspace crate")
    return errors


def check_sources(sources):
    """`sources` maps package-relative paths to text; flags internal surface."""
    errors = []
    for path, text in sorted(sources.items()):
        if not (path.endswith(".rs") or path in {"Cargo.toml", "README.md"}):
            continue
        for pattern, what in FORBIDDEN_SOURCE:
            if pattern.search(text):
                errors.append(f"{path}: carries {what}")
    return errors


def safe_extract(archive, destination):
    """Extract a `.crate` (gzip tar) after rejecting anything but regular files and dirs."""
    with tarfile.open(archive, "r:gz") as tar:
        for member in tar.getmembers():
            path = PurePosixPath(member.name)
            if path.is_absolute() or ".." in path.parts or not (member.isfile() or member.isdir()):
                raise ValueError(f"unsafe .crate member {member.name}")
        tar.extractall(destination, filter="data")


def ancestors_have_manifest(path):
    return any((parent / "Cargo.toml").exists() for parent in [path, *path.parents])


def consumer_files(version):
    """An isolated two-crate consumer workspace: one serialized, one concurrent plugin."""
    requirement = f'vosu-plugin-api = "={version}"'
    test = """
#[cfg(test)]
mod tests {{
    #[test]
    fn exported_entry_creates_dispatches_and_destroys() {{
        unsafe extern "C" fn send(
            _ctx: *mut core::ffi::c_void,
            _message: *const vosu_plugin_api::vosu_message,
        ) -> u32 {{
            vosu_plugin_api::vosu_status::VOSU_OK as u32
        }}
        let host = vosu_plugin_api::vosu_host_services {{
            struct_size: core::mem::size_of::<vosu_plugin_api::vosu_host_services>() as u32,
            abi_version: vosu_plugin_api::VOSU_PLUGIN_ABI_MAJOR,
            send: Some(send),
        }};
        let init = vosu_plugin_api::encode(&vosu_plugin_api::Init {{
            plugin_id: "consumer.{name}".into(),
            settings: vosu_plugin_api::CborValue::Null,
            data_dir: std::env::temp_dir(),
        }})
        .unwrap();
        let payload = vosu_plugin_api::encode(&vosu_plugin_api::SessionDecline {{ handle: 1 }}).unwrap();
        let message = vosu_plugin_api::vosu_message {{
            opcode: vosu_plugin_api::vosu_opcode::VOSU_OP_SESSION_DECLINE as u32,
            flags: 0,
            correlation_id: 0,
            payload: vosu_plugin_api::vosu_bytes {{ data: payload.as_ptr(), len: payload.len() as u32 }},
        }};
        // SAFETY: the exported entry returns its own static vtable; `host`,
        // `init` and `message` outlive each call, and the context is
        // destroyed exactly once.
        unsafe {{
            let vtable = &*super::vosu_plugin_entry_v1();
            assert_eq!(vtable.abi_version, vosu_plugin_api::VOSU_PLUGIN_ABI_MAJOR);
            let ctx = (vtable.create.unwrap())(
                &host,
                core::ptr::null_mut(),
                vosu_plugin_api::vosu_bytes {{ data: init.as_ptr(), len: init.len() as u32 }},
            );
            assert!(!ctx.is_null());
            assert_eq!((vtable.dispatch.unwrap())(ctx, &message), vosu_plugin_api::vosu_status::VOSU_OK as u32);
            assert_eq!(super::DECLINES.load(std::sync::atomic::Ordering::SeqCst), 1);
            (vtable.destroy.unwrap())(ctx);
        }}
    }}
}}
"""
    serialized = """use std::sync::atomic::{AtomicU32, Ordering};
use vosu_plugin_api::{Init, Message, Plugin, PluginError, VtableHostServices, export_plugin};

static DECLINES: AtomicU32 = AtomicU32::new(0);

pub struct Serialized {
    _host: VtableHostServices,
    seen: u32,
}

impl Plugin for Serialized {
    fn create(host: VtableHostServices, _init: Init) -> Result<Self, PluginError> {
        Ok(Self { _host: host, seen: 0 })
    }

    fn on_message(&mut self, message: Message, _correlation_id: u64) -> Result<(), PluginError> {
        if let Message::SessionDecline(_) = message {
            self.seen += 1;
            DECLINES.fetch_add(1, Ordering::SeqCst);
        }
        Ok(())
    }
}

export_plugin!(Serialized);
""" + test.format(name="serialized")
    concurrent = """use std::sync::atomic::{AtomicU32, Ordering};
use vosu_plugin_api::{ConcurrentPlugin, Init, Message, PluginError, VtableHostServices, export_plugin};

static DECLINES: AtomicU32 = AtomicU32::new(0);

pub struct Concurrent {
    _host: VtableHostServices,
}

impl ConcurrentPlugin for Concurrent {
    fn create(host: VtableHostServices, _init: Init) -> Result<Self, PluginError> {
        Ok(Self { _host: host })
    }

    fn on_message(&self, message: Message, _correlation_id: u64) -> Result<(), PluginError> {
        if let Message::SessionDecline(_) = message {
            DECLINES.fetch_add(1, Ordering::SeqCst);
        }
        Ok(())
    }
}

export_plugin!(concurrent Concurrent);
""" + test.format(name="concurrent")

    def member(name):
        return f"""[package]
name = "{name}"
version = "0.1.0"
edition = "2024"
publish = false

[lib]
crate-type = ["cdylib", "rlib"]

[dependencies]
{requirement}
"""

    return {
        "Cargo.toml": '[workspace]\nmembers = ["serialized", "concurrent"]\nresolver = "3"\n',
        "serialized/Cargo.toml": member("consumer-serialized"),
        "serialized/src/lib.rs": serialized,
        "concurrent/Cargo.toml": member("consumer-concurrent"),
        "concurrent/src/lib.rs": concurrent,
    }


def private_surface_probes(version):
    """Consumers that must NOT build: each names a removed private SDK surface (AF.9)."""
    def crate(dependency, source):
        return {
            "Cargo.toml": f"""[package]
name = "private-probe"
version = "0.1.0"
edition = "2024"
publish = false

[workspace]

[dependencies]
{dependency}
""",
            "src/lib.rs": source,
        }

    plain = f'vosu-plugin-api = "={version}"'
    probes = {}
    for feature in ("unstable-sync-reads", "bundled"):
        probes[f"feature {feature}"] = (
            crate(f'vosu-plugin-api = {{ version = "={version}", features = ["{feature}"] }}', ""),
            r"does not (have|contain) (that|this) feature",
        )
    probes["export_plugin!(bundled ...)"] = (
        crate(
            plain,
        """pub struct P;
impl vosu_plugin_api::Plugin for P {
    fn create(_: vosu_plugin_api::VtableHostServices, _: vosu_plugin_api::Init) -> Result<Self, vosu_plugin_api::PluginError> { Ok(P) }
    fn on_message(&mut self, _: vosu_plugin_api::Message, _: u64) -> Result<(), vosu_plugin_api::PluginError> { Ok(()) }
}
vosu_plugin_api::export_plugin!(bundled P);
""",
        ),
        r"no rules expected",
    )
    probes["PlanMemory"] = (
        crate(plain, "pub use vosu_plugin_api::PlanMemory;\n"),
        r"no `PlanMemory` in the root",
    )
    return probes


def check_consumer_metadata(metadata, extracted, checkout=ROOT):
    """The consumer resolved the SDK from the extracted archive, featureless, and nothing from this checkout."""
    errors = []
    extracted = Path(extracted).resolve()
    sdk = [p for p in metadata["packages"] if p["name"] == CRATE]
    if len(sdk) != 1:
        errors.append(f"expected exactly one {CRATE} package, found {len(sdk)}")
    for package in sdk:
        if Path(package["manifest_path"]).resolve().parent != extracted:
            errors.append(f"{CRATE} resolved from {package['manifest_path']}, not the extracted archive")
        if package["features"]:
            errors.append(f"{CRATE} exposes features {sorted(package['features'])}")
    for node in metadata.get("resolve", {}).get("nodes", []):
        if node["id"] in {p["id"] for p in sdk} and node.get("features"):
            errors.append(f"{CRATE} resolved with features {node['features']}")
    for package in metadata["packages"]:
        manifest = Path(package["manifest_path"]).resolve()
        if checkout.resolve() in manifest.parents:
            errors.append(f"{package['name']} resolved from this checkout ({manifest})")
        if package["name"].startswith("vosu-") and package["name"] != CRATE:
            errors.append(f"consumer graph contains workspace crate {package['name']}")
    return errors


def run(cmd, cwd, env):
    print(f"$ {' '.join(cmd)}  (in {cwd})", flush=True)
    completed = subprocess.run(cmd, cwd=cwd, env=env, text=True, capture_output=True)
    if completed.returncode != 0:
        sys.stderr.write(completed.stdout[-6000:] + completed.stderr[-6000:])
        raise SystemExit(f"command failed ({completed.returncode}): {' '.join(cmd)}")
    return completed.stdout + completed.stderr


def sdk_version():
    with open(CRATE_DIR / "Cargo.toml", "rb") as handle:
        return tomllib.load(handle)["package"]["version"]


def verify(args):
    version = sdk_version()
    target_dir = Path(os.environ.get("CARGO_TARGET_DIR", ROOT / "target"))
    if args.crate:
        archive = Path(args.crate).resolve()
    else:
        run(["cargo", "package", "--locked", "-p", CRATE], ROOT, dict(os.environ))
        archive = target_dir / "package" / f"{CRATE}-{version}.crate"
    digest = hashlib.sha256(archive.read_bytes()).hexdigest()
    prefix = f"{CRATE}-{version}"
    print(f"package {archive}\nsha256 {digest}")

    with tarfile.open(archive, "r:gz") as tar:
        members = [(m.name, m.isfile()) for m in tar.getmembers() if not m.isdir()]
        sources = {}
        for member in tar.getmembers():
            if member.isfile():
                sources[member.name[len(prefix) + 1 :]] = tar.extractfile(member).read().decode("utf-8", "replace")
    globs = include_globs((CRATE_DIR / "Cargo.toml").read_text(encoding="utf-8"))
    files, errors = check_members(prefix, members, globs)
    errors += check_normalized_manifest(sources.get("Cargo.toml", ""))
    errors += check_sources({path: text for path, text in sources.items() if path != "Cargo.toml.orig"})
    if errors:
        raise SystemExit("package contents rejected:\n  " + "\n  ".join(errors))
    print(f"{len(files)} files:\n  " + "\n  ".join(files))

    env = dict(os.environ)
    env["RUSTUP_TOOLCHAIN"] = pinned_toolchain()
    env.pop("CARGO_TARGET_DIR", None)
    env.pop("RUSTC_WORKSPACE_WRAPPER", None)
    offline = ["--offline"] if args.offline else []
    work = Path(tempfile.mkdtemp(prefix="vosu-sdk-package-", dir=args.work_dir)).resolve()
    if ancestors_have_manifest(work):
        raise SystemExit(f"{work} has a Cargo.toml ancestor; choose --work-dir outside any workspace")
    safe_extract(archive, work)
    extracted = work / prefix
    env["CARGO_TARGET_DIR"] = str(work / "target")
    output = run(["cargo", "test", "--locked", *offline], extracted, env)
    passed = sum(int(n) for n in re.findall(r"test result: ok\. (\d+) passed", output))
    print(f"standalone package tests: {passed} passed")
    if passed == 0:
        raise SystemExit("the extracted package ran no tests")

    consumer = work / "consumer"
    for relative, text in consumer_files(version).items():
        path = consumer / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    # Seed the consumer's lock with the package's own pins so resolution
    # works offline from the local Cargo cache; cargo prunes what is unused.
    (consumer / "Cargo.lock").write_bytes((extracted / "Cargo.lock").read_bytes())
    patch = ["--config", f"patch.crates-io.{CRATE}.path={json.dumps(str(extracted))}"]
    metadata = json.loads(
        subprocess.run(
            ["cargo", *patch, "metadata", "--format-version", "1", *offline],
            cwd=consumer,
            env=env,
            text=True,
            capture_output=True,
            check=True,
        ).stdout
    )
    errors = check_consumer_metadata(metadata, extracted)
    if errors:
        raise SystemExit("consumer resolution rejected:\n  " + "\n  ".join(errors))
    output = run(["cargo", *patch, "test", "--workspace", *offline], consumer, env)
    passed = sum(int(n) for n in re.findall(r"test result: ok\. (\d+) passed", output))
    if passed != 2:
        raise SystemExit(f"consumer ran {passed} tests; expected the serialized and concurrent export tests")
    run(["cargo", *patch, "build", "--workspace", "--release", *offline], consumer, env)
    print(f"isolated consumer: serialized and concurrent cdylib exports built and tested ({passed} tests)")

    for name, (files, expected) in private_surface_probes(version).items():
        probe = work / "probes" / re.sub(r"[^a-z]+", "-", name.lower()).strip("-")
        for relative, text in files.items():
            path = probe / relative
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
        (probe / "Cargo.lock").write_bytes((extracted / "Cargo.lock").read_bytes())
        completed = subprocess.run(
            ["cargo", *patch, "check", *offline], cwd=probe, env=env, text=True, capture_output=True
        )
        if completed.returncode == 0:
            raise SystemExit(f"private SDK surface probe built: {name}")
        if not re.search(expected, completed.stderr):
            sys.stderr.write(completed.stderr[-4000:])
            raise SystemExit(f"private SDK surface probe {name} failed for another reason")
        print(f"private surface unavailable to consumers: {name}")

    if args.keep:
        print(f"work directory {work} (kept)")
    else:
        shutil.rmtree(work)
    return 0


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    verify_parser = sub.add_parser("verify", help="package (or take --crate) and verify it outside the workspace")
    verify_parser.add_argument("--crate", help="an existing vosu-plugin-api .crate instead of running cargo package")
    verify_parser.add_argument("--work-dir", help="parent of the temporary work directory (default: system temp)")
    verify_parser.add_argument("--offline", action="store_true", help="pass --offline to every consumer cargo call")
    verify_parser.add_argument("--keep", action="store_true", help="keep the temporary work directory")
    args = parser.parse_args()
    return verify(args)


if __name__ == "__main__":
    sys.exit(main())
